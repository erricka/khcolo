def review():
    company = load("company.json")
    services = load("services.json")
    products = load("products.json")

    out = [
        "# Content review list",
        "",
        "Facts that need the owner's confirmation before or after launch. Nothing here was filled in with invented",
        "details; where a source was contradictory or unsupported, the public page uses cautious wording or omits",
        "the value, and the original is recorded here. The same notes are stored in the database (`review_notes`)",
        "and returned by `GET /api/v1/admin/review`.",
        "",
        "Generated by `scripts/build_docs.py` from `/content`, plus the cross-cutting items in the first section.",
        "",
    ]
    for title, items in EXTRA_REVIEW:
        out += [f"## {title}", ""]
        out += [f"- [ ] {i}" for i in items]
        out.append("")

    out += ["## Company record", ""]
    out += [f"- [ ] {n}" for n in company["review"]["notes"]]
    out.append("")

    out += ["## Service pages", ""]
    for s in sorted(services, key=lambda s: s["position"]):
        out.append(f"### {s['name']} — `/{s['slug']}/`")
        out.append(f"Source: {s['sourceUrl']}")
        out.append("")
        out += [f"- [ ] {n}" for n in s["review"]["notes"]]
        out.append("")

    out += ["## Products", ""]
    for p in products:
        notes = p["review"]["notes"]
        if not notes:
            continue
        out.append(f"### {p['name']} — `/product/{p['slug']}/`")
        out += [f"- [ ] {n}" for n in notes]
        out.append("")
    clean = [p["name"] for p in products if not p["review"]["notes"]]
    out += [
        "### Products with no specific issues",
        "",
        "Specifications are as listed on the old site and still need a general check against current",
        "manufacturer data: " + ", ".join(clean) + ".",
        "",
    ]
    (DOCS / "content-review.md").write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    DOCS.mkdir(exist_ok=True)
    inventory()
    review()
    print("Wrote docs/page-inventory.md and docs/content-review.md")
