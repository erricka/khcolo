#!/usr/bin/env python3
"""Regenerate docs/page-inventory.md and docs/content-review.md from /content.

    python3 scripts/build_docs.py

Run it after editing the content files so the inventory and the review list stay
in step with what the site actually publishes.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "content"
DOCS = ROOT / "docs"
SITE = "https://khcolo.com"


def load(name):
    return json.loads((CONTENT / name).read_text(encoding="utf-8"))


def cell(text):
    return str(text or "—").replace("|", "\\|").replace("\n", " ")


def inventory():
    pages = load("pages.json")
    services = load("services.json")
    categories = load("categories.json")
    products = load("products.json")
    redirects = load("redirects.json")

    rows = []
    for p in pages:
        rows.append((p.get("sourceUrl") or "New page", p["path"], p["title"], p["description"], p["h1"],
                     p["schemaType"], "Yes" if p["indexable"] else "No"))
    for s in sorted(services, key=lambda s: s["position"]):
        rows.append((s["sourceUrl"], f"/{s['slug']}/", s["seo"]["title"], s["seo"]["description"], s["h1"],
                     "Service, BreadcrumbList", "Yes"))
    for c in categories:
        rows.append((c["sourceUrl"], f"/product-category/{c['slug']}/", c["seo"]["title"], c["seo"]["description"],
                     c["h1"], "CollectionPage (ItemList), BreadcrumbList", "Yes"))
    for p in products:
        h1 = f"{p['name']} {p['type']}" + (f" · {p['variant']}" if p.get("variant") else "")
        rows.append((p["sourceUrls"][0], f"/product/{p['slug']}/", p["seo"]["title"], p["seo"]["description"], h1,
                     "Product, BreadcrumbList", "Yes"))

    out = [
        "# Page inventory",
        "",
        "Generated by `scripts/build_docs.py` from the files in `/content`. Every indexable URL below is in",
        "`/sitemap.xml`, carries a self-referencing canonical on `https://khcolo.com`, and has exactly one H1.",
        "Existing routes were kept; only the duplicate T46U listing and the WordPress feeds changed.",
        "",
        f"**{len(rows)} indexable pages** ({len(pages)} fixed pages, {len(services)} services, "
        f"{len(categories)} categories, {len(products)} products).",
        "",
        "| Source URL | New / canonical URL | Title | Meta description | H1 | Structured data | Indexable |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        out.append("| " + " | ".join(cell(x) for x in r) + " |")

    out += [
        "",
        "## Redirects and removed URLs",
        "",
        "| Old URL | Result | Note |",
        "| --- | --- | --- |",
    ]
    for r in redirects["redirects"]:
        code = "308" if r.get("permanent", True) else "307"
        out.append(f"| {SITE}{r['source']} | {code} → {r['destination']} | {cell(r.get('note'))} |")
    for g in redirects["gone"]:
        out.append(f"| {SITE}{g['path']} | 410 Gone | {cell(g.get('note'))} |")
    out += [
        f"| {SITE}/proxmox-backup-server | 404 (unchanged) | Already 404 on the old site. Link removed; no thin page created. |",
        f"| `//any-path/` (doubled slash) | 308 → single-slash URL | The old site linked to `//3cx-bitrix24-integration/`. |",
        "| `/any-path` (no trailing slash) | 308 → `/any-path/` | Trailing-slash policy matches the old WordPress URLs. |",
        "",
        "### Non-indexable routes",
        "",
        "| Route | Handling |",
        "| --- | --- |",
        "| `/api/inquiry/`, `/api/revalidate/` | Site route handlers; disallowed in robots.txt, POST only. |",
        "| `/api/v1/*` (FastAPI) | Not exposed publicly in the compose setup; every response sends `X-Robots-Tag: noindex`. Admin endpoints need a bearer token. |",
        "| Catalog filter URLs (`?type=`, `?brand=`, `?q=`) | Same page; canonical points to the clean category URL. |",
        "| 404 page | `noindex`. |",
        "| Any deployment with `SITE_ENV` ≠ `production` | robots.txt disallows everything and every response sends `X-Robots-Tag: noindex, nofollow`. |",
    ]
    (DOCS / "page-inventory.md").write_text("\n".join(out) + "\n", encoding="utf-8")


